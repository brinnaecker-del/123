FIN_CODES = {"000783", "002142", "002673", "600030", "600918", "600926", "600958", "600999", "601059", "601066",
             "601077", "601108", "601211", "601665", "601818", "601998"}   # 银行、证券
CASES = {"688228": "开普云", "300229": "拓尔思", "600941": "中国移动"}


def load(path, sheet):
    rows = list(openpyxl.load_workbook(path, read_only=True)[sheet].iter_rows(values_only=True))
    return rows[0], rows[1:]


fh, frows = load(FIN, "财务数据")
fi = {h: i for i, h in enumerate(fh)}
fin = {(r[0], r[1]): r for r in frows}
dh, drows = load(DR, "汇总")
ph, prows = load(DR, "公司面板")
names = {r[0]: r[1] for r in prows}
names["688066"] = "航天宏图"

COLS = {"ta": "总资产_期末(元)", "ta0": "总资产_期初(元)", "rev": "营业总收入_本期(元)", "rev0": "营业总收入_上期(元)",
        "ni": "净利润_本期(元)", "ni0": "净利润_上期(元)", "np": "归母净利润_本期(元)", "np0": "归母净利润_上期(元)",
        "rd": "研发费用_本期(元)", "rdi": "研发投入合计(元)", "rdc": "研发投入资本化金额(元)"}

out, fixlog = [], []
for r in drows:
    year, code = str(r[0]), str(r[1])
    f = fin[(year, code)]
    v = {k: f[fi[c]] for k, c in COLS.items()}
    note = ""
    if (year, code) in FIX:
        vals, note = FIX[(year, code)]
        for k, x in vals.items():
            fixlog.append([year, code, names.get(code, r[2]), k, v[k], x, note])
            v[k] = x
    end, begin = r[6], r[7] or 0
    flow = end - begin       # 当期新增 = 期末 - 期初；2024 年绝大多数期初为 0，天威视讯等 4 家列示了 2024 年以前已资本化的余额
    ni = v["ni"] if v["ni"] is not None else v["np"]     # 净利润缺失时用归母净利润
    profit_src = "净利润" if v["ni"] is not None else "归母净利润"
    loss = ni is not None and ni < 0
    down = v["np"] is not None and v["np0"] is not None and v["np"] < v["np0"]
    state = "亏损" if loss else ("下滑" if down else "稳健")
    row = dict(
        年度=year, 代码=code, 简称=names.get(code, r[2]), 行业="金融" if code in FIN_CODES else "非金融",
        案例企业=CASES.get(code, ""),
        入表期末=end, 入表期初=begin, 测算入表额=flow,
        总资产=v["ta"], 营业收入=v["rev"], 净利润=ni, 利润口径=profit_src, 净利润上期=v["ni0"],
        归母净利润=v["np"], 归母净利润上期=v["np0"], 研发费用=v["rd"], 研发投入合计=v["rdi"], 研发投入资本化=v["rdc"],
        经营状态=state,
    )
    ta, rev = v["ta"], v["rev"]
    row["存量相对重要性%"] = end / ta * 100 if ta else None
    row["相对重要性%"] = flow / ta * 100 if ta else None
    row["净利率%"] = ni / rev * 100 if (ni is not None and rev) else None
    row["净利率影响pp"] = flow / rev * 100 if rev else None
    row["还原后净利润"] = ni - flow if ni is not None else None
    row["还原后净利率%"] = (ni - flow) / rev * 100 if (ni is not None and rev) else None
    row["入表额占净利润绝对值%"] = flow / abs(ni) * 100 if ni else None
    row["盈亏反转"] = int(ni is not None and ((ni > 0 and ni - flow < 0) or (ni < 0 and ni - flow > 0)))
    row["总资产对数"] = math.log(ta) if ta else None
    row["财务数据人工核对"] = note
    out.append(row)

header = list(out[0].keys())
