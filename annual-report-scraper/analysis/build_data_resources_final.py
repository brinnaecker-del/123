bold = Font(bold=True); head_fill = PatternFill("solid", fgColor="DDEBF7")
def add(title, header, rows, widths=None):
    ws = wb.create_sheet(title)
    if header:
        ws.append(header)
        for c in ws[1]:
            c.font = bold; c.fill = head_fill; c.alignment = Alignment(wrap_text=True, vertical="center")
        ws.freeze_panes = "A2"
    for r in rows:
        ws.append(r)
    for col in ws.columns:
        width = max(len(str(c.value or "")) for c in list(col)[:200])
        ws.column_dimensions[col[0].column_letter].width = min(max(8, width * 1.6), 60)
