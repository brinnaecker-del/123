function Item(n, loc, orig, prob, fix) {
  const blocks = [
    P([T(`${n}. `, { b: true }), T(loc, { b: true })], { after: 60 }),
    P([T('原文：', { b: true, color: '595959' }), ...IB(orig, { color: '404040' })],
      { indent: { left: 420, hanging: 0 }, after: 50 }),
    P([T('问题：', { b: true, color: '595959' }), ...IB(prob)],
      { indent: { left: 420 }, after: 50 }),
    P([T('建议：', { b: true, color: '1F4E79' }), ...IB(fix)],
      { indent: { left: 420 }, after: 160 }),
  ];
  return blocks;
}

