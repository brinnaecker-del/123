// 表格
function TBL(headers, rows, widths, opts = {}) {
  const total = widths.reduce((a, b) => a + b, 0);
  const cols = widths.map(w => Math.round(w / total * W));
  const cell = (txt, i, hd) => new TableCell({
    width: { size: cols[i], type: WidthType.DXA },
    shading: hd ? { type: ShadingType.CLEAR, fill: opts.headFill || BLUE, color: 'auto' } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    children: String(txt).split('\n').map((line, k) => new Paragraph({
      children: parseInline(line, { size: 19, b: hd }),
      spacing: { line: 280, before: 0, after: k === String(txt).split('\n').length - 1 ? 0 : 60 },
      alignment: opts.center && opts.center.includes(i) ? AlignmentType.CENTER : undefined,
    })),
  });
  return new Table({
    columnWidths: cols,
    width: { size: W, type: WidthType.DXA },
    rows: [
      new TableRow({ tableHeader: true, children: headers.map((h, i) => cell(h, i, true)) }),
      ...rows.map(r => new TableRow({ children: r.map((c, i) => cell(c, i, false)) })),
    ],
  });
}

// 极简行内标记：**粗体**
function parseInline(s, o = {}) {
  const out = [];
  for (const part of String(s).split(/(\*\*[^*]+\*\*)/g)) {
    if (!part) continue;
    if (part.startsWith('**') && part.endsWith('**'))
      out.push(T(part.slice(2, -2), { ...o, b: true }));
    else out.push(T(part, o));
  }
  return out.length ? out : [T('', o)];
}
const IB = (s, o = {}) => parseInline(s, { size: 21, ...o });

