def parse(s):
    nums = []
    for part in re.split('[,，]', s):
        a = re.split('[-–—]', part)
        nums += list(range(int(a[0]), int(a[-1]) + 1))
    return nums

els = list(body)
refs_start = [i for i, el in enumerate(els) if el.tag == w('p') and text_of(el) == '参考文献'][0]
seen = []
for el in els[:refs_start]:
    for r in el.iter(w('r')):
        rpr = r.find(w('rPr'))
        va = rpr.find(w('vertAlign')) if rpr is not None else None
        if va is not None and va.get(w('val')) == 'superscript':
            m = re.fullmatch(r'\[([\d,\-]+)\]', ''.join(t.text or '' for t in r.findall(w('t'))))
            if m:
                for n in parse(m.group(1)):
                    if n not in seen:
                        seen.append(n)
nrefs = sum(1 for el in els[refs_start + 1:] if re.match(r'\[\d+\] ', text_of(el)))
assert seen == list(range(1, nrefs + 1)), (seen, nrefs)
print('引注 1…%d 顺序连续，文后 %d 条' % (len(seen), nrefs))

