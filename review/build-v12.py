def text_of(p):
    return ''.join(t.text or '' for t in p.iter(w('t')))

def base_rpr(p):
    for r in p.iter(w('r')):
        if r.find(w('t')) is None:
            continue
        rpr = r.find(w('rPr'))
        if rpr is not None and rpr.find(w('vertAlign')) is not None:
            continue
        return copy.deepcopy(rpr) if rpr is not None else etree.Element(w('rPr'))
    return etree.Element(w('rPr'))

def make_run(rpr, text, valign=None):
    r = etree.Element(w('r'))
    rp = copy.deepcopy(rpr)
    for va in rp.findall(w('vertAlign')):
        rp.remove(va)
    if valign:
        va = etree.SubElement(rp, w('vertAlign')); va.set(w('val'), valign)
    if len(rp):
        r.append(rp)
    t = etree.SubElement(r, w('t')); t.text = text; t.set(XML_SPACE, 'preserve')
    return r

TOKEN = re.compile(r'\^(\[[^\]]+\])')
def rewrite(p, s):
    rpr = base_rpr(p)
    for c in list(p):
        if c.tag != w('pPr'):
            p.remove(c)
    pos = 0
    for m in TOKEN.finditer(s):
        if m.start() > pos:
            p.append(make_run(rpr, s[pos:m.start()]))
        p.append(make_run(rpr, m.group(1), 'superscript'))
        pos = m.end()
    if pos < len(s):
        p.append(make_run(rpr, s[pos:]))

def edit_runs(p, pairs):
    for old, new in pairs:
        hits = [t for t in p.iter(w('t')) if t.text == old]
        assert len(hits) == 1, (old[:20], len(hits))
        hits[0].text = new
        hits[0].set(XML_SPACE, 'preserve')

