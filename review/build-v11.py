def renum(n):
    assert n != 34, '正文仍引用了已删除的[34]'
    return n - 1 if n > 34 else n

def fmt(nums):
    nums = sorted(set(nums)); out = []; i = 0
    while i < len(nums):
        j = i
        while j + 1 < len(nums) and nums[j + 1] == nums[j] + 1:
            j += 1
        out.append(str(nums[i]) if j == i else ('%d-%d' % (nums[i], nums[j]) if j > i + 1 else '%d,%d' % (nums[i], nums[j])))
        i = j + 1
    return '[' + ','.join(out) + ']'

def parse(s):
    nums = []
    for part in re.split('[,，]', s):
        a = re.split('[-–—]', part)
        nums += list(range(int(a[0]), int(a[-1]) + 1))
    return nums

